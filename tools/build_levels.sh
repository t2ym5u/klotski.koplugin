#!/bin/bash
# Rebuilds levels_data.lua: one candidate run per block set (in parallel),
# then the selection. Deterministic. About a minute on an 8-core desktop.
set -e
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
for e in 2 3 4; do
    for v in 0 1 2 3 4 5 6; do
        for h in 0 1 2 3 4 5 6; do
            s=$((16 - e - 2 * v - 2 * h))
            if [ $s -ge 0 ] && [ $s -le 8 ]; then
                luajit "$here/gen_levels.lua" $v $h $s $e > "$tmp/V${v}H${h}S${s}E${e}.txt" &
            fi
        done
    done
    wait
done
out="$here/../levels_data.lua"
{
    echo "-- Level bank, generated by tools/build_levels.sh -- do not edit by hand."
    echo "-- One band header per difficulty, then one line per level: 20-character"
    echo "-- tray (row by row, see solver.lua), its optimal moves and that solution"
    echo "-- packed (Solver.packPath); the classics also carry a name key. Kept as a"
    echo "-- .lua file so PluginManager ships it."
    echo "return [["
    luajit "$here/merge_levels.lua" "$here/classics.txt" "$tmp"/*.txt
    echo "]]"
} > "$out"
rm -rf "$tmp"
